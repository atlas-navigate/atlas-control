#!/usr/bin/env python3
"""Regenerate requirements.lock: exact versions + wheel hashes for aarch64/cp312.

Versions are pinned to what the working development environment runs (its
`pip freeze`), so a release never silently jumps to an untested major
version. Needs Internet (PyPI). Commit the resulting requirements.lock.

    tools/release/lock.py [--python /atlas_data/atlas-control/venv/bin/python3]
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

import _common

WHEEL = re.compile(r"^(?P<name>[A-Za-z0-9_.]+)-(?P<version>[^-]+)-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python", default=sys.executable)
    args = ap.parse_args()
    req = os.path.join(_common.REPO, "requirements.txt")
    with tempfile.TemporaryDirectory() as tmp:
        freeze = subprocess.run([args.python, "-m", "pip", "list", "--format=freeze"],
                                capture_output=True, text=True, check=True).stdout
        constraints = os.path.join(tmp, "constraints.txt")
        with open(constraints, "w") as f:
            f.write("\n".join(l for l in freeze.splitlines() if "==" in l and not l.startswith("-e")))
        wheels = os.path.join(tmp, "wheels")
        subprocess.run([args.python, "-m", "pip", "download", "--disable-pip-version-check",
                        "--only-binary=:all:", "-r", req, "-c", constraints, "-d", wheels],
                       check=True)
        lines = []
        for fn in sorted(os.listdir(wheels), key=str.lower):
            m = WHEEL.match(fn)
            if not m:
                sys.exit(f"unexpected download {fn}")
            digest = hashlib.sha256(open(os.path.join(wheels, fn), "rb").read()).hexdigest()
            name = m.group("name").replace("_", "-").lower()
            lines.append(f"{name}=={m.group('version')} --hash=sha256:{digest}")
    out = os.path.join(_common.REPO, "requirements.lock")
    with open(out, "w") as f:
        f.write("# Generated by tools/release/lock.py — exact wheels for aarch64 / CPython 3.12.\n")
        f.write("# Do not edit by hand; change requirements.txt and re-run the tool.\n")
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(lines)} packages)")


if __name__ == "__main__":
    main()
